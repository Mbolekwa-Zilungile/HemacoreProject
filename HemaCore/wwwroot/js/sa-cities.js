window.attachCityDropdown = function (cityInputId, postalInputId, provinceInputId) {
    var cityInput = document.getElementById(cityInputId);
    var postalInput = document.getElementById(postalInputId);
    var provinceInput = provinceInputId ? document.getElementById(provinceInputId) : null;

    if (!cityInput || !postalInput) return;
    if (cityInput.dataset.saCityAttached === "true") return;
    cityInput.dataset.saCityAttached = "true";

    var wrapper = document.createElement("div");
    wrapper.className = "sa-city-wrapper";
    wrapper.style.position = "relative";
    wrapper.style.width = "100%";

    cityInput.parentNode.insertBefore(wrapper, cityInput);
    wrapper.appendChild(cityInput);

    var dropdown = document.createElement("div");
    dropdown.className = "sa-city-dropdown";
    dropdown.style.position = "absolute";
    dropdown.style.zIndex = "1000";
    dropdown.style.left = "0";
    dropdown.style.right = "0";
    dropdown.style.top = "100%";
    dropdown.style.background = "#fff";
    dropdown.style.border = "1px solid #e2e8f0";
    dropdown.style.borderRadius = "12px";
    dropdown.style.boxShadow = "0 10px 30px rgba(0,0,0,0.12)";
    dropdown.style.maxHeight = "260px";
    dropdown.style.overflowY = "auto";
    dropdown.style.display = "none";
    dropdown.style.marginTop = "4px";
    wrapper.appendChild(dropdown);

    var currentMatches = [];
    var highlightedIndex = -1;

    function clearDropdown() {
        dropdown.innerHTML = "";
        dropdown.style.display = "none";
        currentMatches = [];
        highlightedIndex = -1;
    }

    function getProvinceFilter() {
        if (!provinceInput) return null;
        var v = provinceInput.value;
        return v && v.trim() !== "" ? v.trim() : null;
    }

    function searchCities(term) {
        var provinceFilter = getProvinceFilter();
        var lowerTerm = (term || "").toLowerCase().trim();

        var matches = window.SA_CITY_LIST.filter(function (entry) {
            if (provinceFilter && entry.province !== provinceFilter) return false;
            if (lowerTerm === "") return true;
            return entry.key.indexOf(lowerTerm) !== -1;
        });

        var seen = {};
        matches = matches.filter(function (m) {
            var k = m.city + "|" + m.postal;
            if (seen[k]) return false;
            seen[k] = true;
            return true;
        });

        return matches;
    }

    function highlightItem(index) {
        dropdown.querySelectorAll(".sa-city-item").forEach(function (el, i) {
            el.style.background = (i === index) ? "#eef2ff" : "#fff";
        });
        highlightedIndex = index;
    }

    function selectCity(entry) {
        cityInput.value = entry.city;
        postalInput.value = entry.postal;

        if (provinceInput && entry.province) {
            var exists = Array.prototype.some.call(
                provinceInput.options,
                function (o) { return o.value === entry.province; }
            );
            if (exists) provinceInput.value = entry.province;
        }

        cityInput.dispatchEvent(new Event("input", { bubbles: true }));
        cityInput.dispatchEvent(new Event("change", { bubbles: true }));
        postalInput.dispatchEvent(new Event("input", { bubbles: true }));
        postalInput.dispatchEvent(new Event("change", { bubbles: true }));

        clearDropdown();
    }

    function renderDropdown(matches) {
        dropdown.innerHTML = "";
        if (matches.length === 0) { dropdown.style.display = "none"; return; }

        var shown = matches.slice(0, 50);

        shown.forEach(function (entry, idx) {
            var item = document.createElement("div");
            item.className = "sa-city-item";
            item.style.padding = "10px 14px";
            item.style.cursor = "pointer";
            item.style.borderBottom = "1px solid #f1f5f9";
            item.style.fontSize = "0.9rem";
            item.style.color = "#2d3748";
            item.style.display = "flex";
            item.style.justifyContent = "space-between";
            item.style.alignItems = "center";
            item.style.gap = "8px";

            var left = document.createElement("span");
            left.textContent = entry.city;

            var right = document.createElement("span");
            right.textContent = entry.postal;
            right.style.color = "#718096";
            right.style.fontSize = "0.8rem";
            right.style.fontFamily = "monospace";

            item.appendChild(left);
            item.appendChild(right);

            item.addEventListener("mousedown", function (e) {
                e.preventDefault();
                selectCity(entry);
            });

            item.addEventListener("mouseenter", function () { highlightItem(idx); });
            dropdown.appendChild(item);
        });

        dropdown.style.display = "block";
        highlightedIndex = -1;
    }

    cityInput.addEventListener("input", function () {
        currentMatches = searchCities(this.value);
        renderDropdown(currentMatches);
    });

    cityInput.addEventListener("focus", function () {
        currentMatches = searchCities(this.value);
        renderDropdown(currentMatches);
    });

    cityInput.addEventListener("blur", function () {
        setTimeout(clearDropdown, 150);
    });

    cityInput.addEventListener("keydown", function (e) {
        if (dropdown.style.display === "none" || currentMatches.length === 0) return;
        var shownCount = Math.min(currentMatches.length, 50);

        if (e.key === "ArrowDown") {
            e.preventDefault();
            var next = highlightedIndex + 1;
            if (next >= shownCount) next = 0;
            highlightItem(next);
        } else if (e.key === "ArrowUp") {
            e.preventDefault();
            var prev = highlightedIndex - 1;
            if (prev < 0) prev = shownCount - 1;
            highlightItem(prev);
        } else if (e.key === "Enter") {
            if (highlightedIndex >= 0 && highlightedIndex < shownCount) {
                e.preventDefault();
                selectCity(currentMatches[highlightedIndex]);
            }
        } else if (e.key === "Escape") {
            clearDropdown();
        }
    });

    if (provinceInput) {
        provinceInput.addEventListener("change", function () {
            if (document.activeElement === cityInput) {
                currentMatches = searchCities(cityInput.value);
                renderDropdown(currentMatches);
            }
        });
    }
};

