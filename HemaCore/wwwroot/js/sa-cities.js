// ---------- FLAT SUBURB LIST (alphabetical) ----------
window.SA_SUBURB_LIST = (function () {
    var list = [];

    Object.keys(window.SA_SUBURBS).forEach(function (cityName) {
        var cityEntry = null;
        for (var i = 0; i < window.SA_CITY_LIST.length; i++) {
            if (window.SA_CITY_LIST[i].city === cityName) {
                cityEntry = window.SA_CITY_LIST[i];
                break;
            }
        }

        var province = cityEntry ? cityEntry.province : "";
        var postal = cityEntry ? cityEntry.postal : "";

        window.SA_SUBURBS[cityName].forEach(function (suburb) {
            list.push({
                suburb: suburb,
                city: cityName,
                postal: postal,
                province: province,
                key: suburb.toLowerCase()
            });
        });
    });

    list.sort(function (a, b) {
        var s = a.suburb.localeCompare(b.suburb);
        if (s !== 0) return s;
        return a.city.localeCompare(b.city);
    });

    return list;
})();

