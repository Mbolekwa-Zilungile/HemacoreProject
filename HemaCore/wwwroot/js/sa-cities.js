// ---------- FLAT CITY LIST (alphabetical) ----------
window.SA_CITY_LIST = (function () {
    var list = [];
    Object.keys(window.SA_CITIES).forEach(function (province) {
        window.SA_CITIES[province].forEach(function (entry) {
            list.push({
                city: entry.city,
                postal: entry.postal,
                province: province,
                key: (entry.city + " " + province).toLowerCase()
            });
        });
    });

    list.sort(function (a, b) {
        var c = a.city.localeCompare(b.city);
        if (c !== 0) return c;
        return a.province.localeCompare(b.province);
    });

    return list;
})();

